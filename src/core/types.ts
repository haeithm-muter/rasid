/**
 * نماذج البيانات المشتركة لكل المشروع.
 *
 * هذا الملف هو العقد بين طبقة الإدخال (المحوّلات) وبقية الأجزاء:
 * الجزء 2 (محرك الكشف) والجزء 3 (الواجهة) يستهلكان `Transaction[]` فقط.
 * لا تضف هنا أي شيء يعتمد على المتصفح أو React.
 */

/** اتجاه العملية: خصم من الحساب أو إيداع فيه. */
export type Direction = 'debit' | 'credit';

/**
 * عملية بنكية واحدة بعد التوحيد — الشكل النهائي الذي تخرجه كل المحوّلات.
 *
 * ثوابت متفق عليها (تعتمد عليها الأجزاء اللاحقة):
 * - `date` بصيغة ISO الصارمة `YYYY-MM-DD` دائماً، بلا وقت وبلا منطقة زمنية.
 * - `amount` قيمة موجبة **دائماً**؛ الإشارة يحملها الحقل `direction` وحده.
 * - `currency` رمز ISO-4217 بثلاثة أحرف كبيرة (مثل `"SAR"`).
 * - `description` الوصف الخام كما ورد في الكشف (بلا تنظيف) — التنظيف مسؤولية
 *   `src/core/merchantNormalizer.ts` حتى يبقى الأصل معروضاً للمستخدم.
 */
export type Transaction = {
  date: string;
  description: string;
  amount: number;
  currency: string;
  direction: Direction;
};

/** صف CSV خام: اسم العمود (بعد قص المسافات) → قيمة الخلية كنص. */
export type CsvRow = Record<string, string>;

/** جدول CSV بعد التحليل: أسماء الأعمدة + الصفوف. */
export type CsvTable = {
  /** أسماء الأعمدة بترتيب ظهورها في الملف. */
  headers: string[];
  /** صفوف البيانات (لا تتضمّن صف الترويسة). */
  rows: CsvRow[];
};

/** صف تعذّر تحويله إلى `Transaction`، محفوظ مع سبب واضح للعرض لاحقاً. */
export type SkippedRow = {
  /** رقم الصف داخل البيانات (يبدأ من 0، بلا احتساب صف الترويسة). */
  index: number;
  /** الصف الخام كما ورد. */
  row: CsvRow;
  /** سبب مقروء بالعربية يشرح لماذا تُخطّي الصف. */
  reason: string;
};

/**
 * ناتج تحويل صفوف CSV: العمليات الصالحة + الصفوف المتخطّاة.
 * الصفوف التالفة لا ترمي خطأً يوقف الملف كله — تُجمع هنا ليقرر المستخدم لاحقاً.
 */
export type ParseResult = {
  transactions: Transaction[];
  skipped: SkippedRow[];
};
